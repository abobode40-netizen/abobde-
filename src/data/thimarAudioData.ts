/**
 * Returns a deterministic daily featured youth lesson updated every day.
 */
export function getDailyFeaturedAudioLesson(): AudioLessonItem {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % AUDIO_LESSONS_LIST.length;
  return AUDIO_LESSONS_LIST[index];
}
